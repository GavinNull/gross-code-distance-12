"""Shared definitions for the SAT encoders and the bulk Pauli-frame model (SM S9, S10).

Labels.  Each check has six CNOTs, one per term of A and B.  Label k = 0..5 stands for A1, A2, A3, B1, B2, B3
(A = x^3 + y + y^2, B = y^3 + x + x^2).  X check i = (a, b) (i = 6a + b) acts with label p < 3 on left qubit
(a, b) + A_p and with label 3 + p on right qubit 72 + (a, b) + B_p; Z check i acts with label 3 + p on left qubit
(a, b) - B_p and with label p on right qubit 72 + (a, b) - A_p.  table()[kind][i][k] = data qubit.

Translations (a, b) act on checks and data qubits (tr); they are code automorphisms that map label k of check i to
label k of check tr(i).

Family(gens): checks of each type are split into the orbits ("classes") of the translation subgroup H generated by
gens; all checks of a class use the same CNOT time per label.  Items = (type, class, label); item index = position
in Family.items.

ext_general(kind, label_orders): extended code for arbitrary per-check label orders (columns = data qubits +
residual suffixes, merged by (H s, L s)), its order-preserving translation group and orbits.  kind "X" = residuals
of X-check orders = X errors = (HZ, LZ) = Z-basis memory; kind "Z" = (HX, LX) = X-basis memory.
"""
from __future__ import annotations

import sys
from functools import lru_cache
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from gross12 import ext as GE                     # noqa: E402
from gross12.code import load_code                # noqa: E402
from gross12.paths import CIRCUIT_FILES           # noqa: E402
from gross12.schedule import load_schedule        # noqa: E402

N2 = 72
LAB = ["A1", "A2", "A3", "B1", "B2", "B3"]
_A = [(3, 0), (0, 1), (0, 2)]          # x^3, y, y^2
_B = [(0, 3), (1, 0), (2, 0)]          # y^3, x, x^2


def _sh(i, d, s=1):
    a, b = divmod(i, 6)
    return ((a + s * d[0]) % 12) * 6 + (b + s * d[1]) % 6


@lru_cache(maxsize=None)
def table():
    T = {"X": np.zeros((N2, 6), int), "Z": np.zeros((N2, 6), int)}
    for i in range(N2):
        for p in range(3):
            T["X"][i, p] = _sh(i, _A[p])
            T["X"][i, 3 + p] = N2 + _sh(i, _B[p])
            T["Z"][i, 3 + p] = _sh(i, _B[p], -1)
            T["Z"][i, p] = N2 + _sh(i, _A[p], -1)
    code = load_code()
    for kind, H in (("X", code.HX), ("Z", code.HZ)):
        for i in range(N2):
            assert sorted(T[kind][i]) == sorted(np.nonzero(H[i])[0].tolist())
    return T


def tr(a, b):
    p = np.array([((i // 6 + a) % 12) * 6 + (i % 6 + b) % 6 for i in range(N2)])
    return p, np.concatenate([p, p + N2])


@lru_cache(maxsize=None)
def HLk(kind):
    c = load_code()
    H, L = (c.HZ, c.LZ) if kind == "X" else (c.HX, c.LX)
    return np.asarray(H, np.uint8) % 2, np.asarray(L, np.uint8) % 2


def subgroup(gens):
    Hs = {(0, 0)}
    while True:
        N = Hs | {((h[0] + g[0]) % 12, (h[1] + g[1]) % 6) for h in Hs for g in gens}
        if N == Hs:
            return sorted(Hs)
        Hs = N


def parse_sub(s):
    if not s:
        return [(0, 0)]
    return [tuple(int(v) for v in g.split(",")) for g in s.split(";")]


G24 = subgroup([(1, 2), (0, 3)])


class Family:
    def __init__(self, gens):
        self.Hs = subgroup(gens)
        self.T = table()
        cls = [-1] * N2
        reps = []
        for i in range(N2):
            if cls[i] >= 0:
                continue
            for h in self.Hs:
                pr, _ = tr(*h)
                cls[int(pr[i])] = len(reps)
            reps.append(i)
        self.cls, self.reps = cls, reps
        self.nc = len(reps)
        self.items = [(ty, k, lab) for ty in "XZ" for k in range(self.nc) for lab in range(6)]
        self.idx = {it: n for n, it in enumerate(self.items)}
        self.touch = [[] for _ in range(144)]
        for ty in "XZ":
            for i in range(N2):
                for lab in range(6):
                    self.touch[int(self.T[ty][i][lab])].append((ty, i, lab))
        self.units = [(ty, k) for ty in "XZ" for k in range(self.nc)]
        self.unit_rep = {(ty, k): self.reps[k] for ty in "XZ" for k in range(self.nc)}
        self.ucls = {ty: list(self.cls) for ty in "XZ"}

    def item(self, ty, check, lab):
        return self.idx[(ty, self.cls[check], lab)]

    def label_of(self, ty, check, q):
        return int(list(self.T[ty][check]).index(q))


@lru_cache(maxsize=None)
def fig12_labels():
    """Fig. 12 per-check orders as label sequences (from data/circuits/fig12.json)."""
    xo, zo = load_schedule(CIRCUIT_FILES["fig12"]).orders()
    T = table()
    out = {}
    for kind, o in (("X", xo), ("Z", zo)):
        inv = [{int(T[kind][i][k]): k for k in range(6)} for i in range(N2)]
        out[kind] = [tuple(inv[i][q] for q in o[i]) for i in range(N2)]
    return out


def parse_orders(s):
    return tuple(tuple(LAB.index(o[i:i + 2]) for i in range(0, 12, 2)) for o in s.split(","))


def colour(col, i):
    m, al, be = col
    a, b = divmod(i, 6)
    return (al * a + be * b) % m


def labord(col, assign):
    return [tuple(assign[colour(col, i)]) for i in range(N2)]


def kernel(col):
    m, al, be = col
    return [(a, b) for a in range(12) for b in range(6) if (al * a + be * b) % m == 0]


def residuals(order):
    return [tuple(sorted(order[l - 1:])) for l in range(2, len(order) + 1)]


def group_of(labord_):
    T = table()
    G = []
    for a in range(12):
        for b in range(6):
            pr, pc = tr(a, b)
            for kind in "XZ":
                for i in range(N2):
                    assert all(T[kind][pr[i]][k] == pc[T[kind][i][k]] for k in range(6))
            if all(tuple(labord_[int(pr[i])]) == tuple(labord_[i]) for i in range(N2)):
                G.append((a, b))
    return G


def ext_general(kind, labord_):
    H, L = HLk(kind)
    T = table()[kind]
    ords = [[int(T[i][k]) for k in labord_[i]] for i in range(N2)]
    supports = [(j,) for j in range(2 * N2)] + [s for o in ords for s in residuals(o)]
    key_idx, keys, sup_class, col_sups = {}, [], [], []
    for S in supports:
        h = (H[:, list(S)].sum(1) % 2).astype(np.uint8)
        lv = (L[:, list(S)].sum(1) % 2).astype(np.uint8)
        if not h.any() and not lv.any():
            sup_class.append(-1)
            continue
        k = h.tobytes() + lv.tobytes()
        if k not in key_idx:
            key_idx[k] = len(keys); keys.append((h, lv)); col_sups.append([])
        sup_class.append(key_idx[k]); col_sups[key_idx[k]].append(S)
    N = len(keys)
    He = np.array([h for h, _ in keys]).T
    Le = np.array([lv for _, lv in keys]).T
    group = group_of(labord_)
    supidx = {S: i for i, S in enumerate(supports)}
    perms = []
    for a, b in group:
        _, pc = tr(a, b)
        P = np.full(N, -1)
        for i, S in enumerate(supports):
            Tt = tuple(sorted(int(pc[j]) for j in S))
            ci, cj = sup_class[i], sup_class[supidx[Tt]]
            if ci < 0:
                assert cj < 0
                continue
            assert P[ci] in (-1, cj)
            P[ci] = cj
        assert sorted(P.tolist()) == list(range(N))
        perms.append(P)
    orb = np.full(N, -1)
    reps = []
    for j in range(N):
        if orb[j] >= 0:
            continue
        o = sorted({int(P[j]) for P in perms})
        orb[o] = len(reps)
        reps.append(j)
    return {"He": He, "Le": Le, "col_sups": col_sups, "perms": np.array(perms), "group": group, "orbit": orb,
            "reps": reps, "N": N}


BASIS_OF_KIND = {"X": "Z", "Z": "X"}


@lru_cache(maxsize=None)
def w11_keys(kind):
    """the 4224 weight-11 extended logicals of `kind` from data/logicals/, as lists of column keys (bytes of H part
    then L part), in file order."""
    code = load_code()
    basis = BASIS_OF_KIND[kind]
    keys = GE.ext_keys_from_file(code, basis)
    return [[keys[j] for j in S] for S in GE.load_w11(basis)]


def reindex(E, keylist):
    k2j = {E["He"][:, j].tobytes() + E["Le"][:, j].tobytes(): j for j in range(E["N"])}
    assert {k for S in keylist for k in S} <= set(k2j), "list column not in this extended code"
    return [tuple(sorted(k2j[k] for k in S)) for S in keylist]


def bf_P(cons, t, P):
    """Bellman-Ford feasibility of the frame-model constraints at CNOT times t (period P); returns potentials or
    None (negative cycle = the logical does not lift)."""
    nodes, edges = {}, []
    for u, w, kd, (i1, i2) in cons:
        iu = nodes.setdefault(u, len(nodes)); iw = nodes.setdefault(w, len(nodes))
        f = (t[i2] - t[i1]) // P + 1
        edges.append((iu, iw, f if kd != "hook-" else -f))
    d = [0] * len(nodes)
    for _ in range(len(nodes) + 1):
        ch = False
        for iu, iw, wt in edges:
            if d[iw] + wt < d[iu]:
                d[iu] = d[iw] + wt; ch = True
        if not ch:
            return {k: d[i] for k, i in nodes.items()}
    return None


def build_kind_data(col, orders):
    """(E, logicals) per kind for the class given by a colouring and per-colour canonical orders."""
    out = {}
    for k in "XZ":
        E = ext_general(k, labord(col, orders[k]))
        out[k] = (E, reindex(E, w11_keys(k)))
    return out


def fig12_kind_data():
    f12 = fig12_labels()
    out = {}
    for k in "XZ":
        E = ext_general(k, f12[k])
        out[k] = (E, reindex(E, w11_keys(k)))
    return out
