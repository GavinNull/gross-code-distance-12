"""Symmetry de-duplication for abelian group-algebra (BB) codes.

Equivalences used (each maps a code to a qubit/check-permutation-equivalent code with identical
n, k, d, Tanner-graph structure; X/Z may be exchanged, which does not change n, k, d):

 E1  translations  A -> g A,  B -> h B  for any g, h in G  (independently).
     [g A | h B] = [A|B] diag(P_g, P_h) is a column permutation of HX; HZ' equals HZ with rows
     permuted by gh and the same column permutation.  -> we normalise each polynomial to contain 1.
 E2  group automorphisms  phi in Aut(G) applied to both A and B (relabels group elements; permutes
     rows and columns consistently).  For Z_l x Z_m this includes x -> x^u, y -> y^v (units),
     x <-> y when l = m, all "shears" x -> x y^c, ..., and inversion g -> g^-1, which gives
     (A, B) -> (A^T, B^T) i.e. X <-> Z duality.
 E3  swap  (A, B) -> (B, A): HX' = HX with the two blocks swapped, HZ' likewise.
 E4  group isomorphism between different (l, m): every Z_l x Z_m is first mapped to its invariant-
     factor form Z_d1 x Z_d2 (d1 | d2), so e.g. (l, m) = (15, 2), (10, 3), (6, 5) all collapse to Z_30.

The canonical key is the lexicographically smallest (sorted A, sorted B) over the orbit generated by
E1–E3 inside Z_d1 x Z_d2, prefixed by (d1, d2).  Codes with equal keys are equivalent; codes with
different keys MAY still be equivalent through some other qubit permutation (the reduction is sound,
not necessarily complete).  Non-abelian 2BGA: only an interface (`canonical_key` falls back to the
raw description) — Aut(G) and the left/right asymmetry are not handled yet.
"""
from __future__ import annotations

from functools import lru_cache

import numpy as np

from search.codes.groups import abelian_automorphisms, invariant_factors, iso_to_canonical


@lru_cache(maxsize=None)
def _canon_tables(l: int, m: int):
    d1, d2 = invariant_factors(l, m)
    N = d1 * d2
    auts = abelian_automorphisms(d1, d2)
    I, J = np.divmod(np.arange(N), d2)
    sub = ((I[:, None] - I[None, :]) % d1) * d2 + (J[:, None] - J[None, :]) % d2  # sub[g,h] = g - h
    phi = iso_to_canonical(l, m)
    return d1, d2, N, auts, sub, phi


def _min_normalised(S: np.ndarray, sub: np.ndarray, N: int) -> np.ndarray:
    """S: (nAut, 3) images. Return (nAut,) codes of min over translations of the sorted triple."""
    # T[a, i, :] = S[a, :] - S[a, i]
    T = sub[S[:, None, :], S[:, :, None]]           # (nAut, 3, 3)
    T = np.sort(T, axis=2)
    code = (T[..., 0] * N + T[..., 1]) * N + T[..., 2]
    return code.min(axis=1)


def canonical_key_abelian(l: int, m: int, a, b) -> tuple:
    d1, d2, N, auts, sub, phi = _canon_tables(l, m)
    A = phi[np.asarray(a)]
    B = phi[np.asarray(b)]
    if len(A) != 3 or len(B) != 3:
        return ("raw", d1, d2, tuple(sorted(A)), tuple(sorted(B)))
    ka = _min_normalised(auts[:, A], sub, N)
    kb = _min_normalised(auts[:, B], sub, N)
    N3 = N ** 3
    key = np.minimum(ka * N3 + kb, kb * N3 + ka).min()
    return (d1, d2, int(key))


def canonical_key(code) -> tuple:
    if code.group.abelian_lm:
        l, m = code.group.abelian_lm
        return canonical_key_abelian(l, m, code.a, code.b)
    return ("nonabelian", code.group.name, tuple(code.a), tuple(code.b))


def key_to_code(key: tuple):
    """Representative BB code (on Z_d1 x Z_d2) of an abelian canonical key."""
    from search.codes.construct import GroupAlgebraCode
    from search.codes.groups import abelian_group
    d1, d2, v = key
    N = d1 * d2
    N3 = N ** 3
    ka, kb = divmod(v, N3)

    def dec(c):
        e2 = c % N
        e1 = (c // N) % N
        e0 = c // (N * N)
        return (e0, e1, e2)

    return GroupAlgebraCode(abelian_group(d1, d2), dec(ka), dec(kb), family="BB")
