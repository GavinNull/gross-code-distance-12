"""Build the [[90,8,10]] part of release/zenodo/ (code matrices, circuits c16 / u16, extended codes, the complete
weight-8 and weight-9 extended-logical lists, the weight-10 upper-bound witness, the per-check-free d_ext <= 8 CNF).

Run from the repository root:
    PYTHONPATH=.:tests:release/zenodo/code uv run python scripts/zenodo/build_bb90.py [CNF [CERTIFY_DIR]]

Sources (internal; no path information is written into the package):
  code matrices        evaluator build_code("bb90-dcirc")
  circuits             search/experiments/e028/c16_spec.json (c16), search/experiments/e028/u16_spec.json (u16),
                       results/E-028-bb90-interleaved/segctl_A1A2A3B2B1B3_A1A2A3B2B1B3.json (s16)
  weight-8/9 lists     results/E-028-bb90-interleaved/w{8,9}_{X,Z}_all_A1A2A3B2B1B3.pkl (project DFS), cross-checked
                       set-for-set against the audit MITM lists results/E-028-audit/ext_c16_{X,Z}.pkl
  witness              results/E-028-bb90-interleaved/inject10_c16_spec.json
  CNF                  regenerated by release/zenodo/code/bb90/dext_free.py (separately; first argument); compared with
                       results/E-028-audit/a6_dext_free_X.cnf (sha256)
  proof record         output directory of `certify.py one CNF DIR bb90_dext_free_X --keep` (second argument):
                       CaDiCaL + drat-trim + cake_lpr; the proof sha256 is compared with the audit proof
                       results/E-028-audit/a6_dext_free_X.drat (5fad1f63...)
Every exported object is cross-checked against the implementation it came from.
"""
import gzip
import hashlib
import json
import pickle
import shutil
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, "tests")
sys.path.insert(0, "release/zenodo/code")

from evaluators.tasks import build_code, get_task                                       # noqa: E402
from evaluators.candidate import parse_schedule as ev_parse, build_circuits as ev_build  # noqa: E402
from evaluators.noise import add_noise                                                   # noqa: E402

from gross12 import schedule as PS, noise as PN                                          # noqa: E402
from bb90 import bbcode as BC, ext as BE                                                 # noqa: E402

REL = Path("release/zenodo")
DATA = REL / "data"
evcode, _ = build_code(get_task("bb90-dcirc"), None)
rows = lambda M: [np.flatnonzero(r).tolist() for r in np.asarray(M) % 2]  # noqa: E731

# ---------------------------------------------------------------- code
code_json = {
    "description": "Bivariate bicycle code [[90,8,10]] of arXiv:2308.07915 (Table 3): l=15, m=3, A = x^9+y+y^2, "
                   "B = 1+x^2+x^7, HX = [A|B], HZ = [B^T|A^T]. Qubit/check index 3a+b for x^a y^b; left block = "
                   "qubits 0..44, right block = 45..89. Each matrix is given as a list of rows, each row as the sorted "
                   "list of the columns where it is 1. LX: 8 X-type logical operators, LZ: 8 Z-type logical operators "
                   "(the observables of the X- and Z-basis memories; all logical lists refer to these rows).",
    "n": 90, "k": 8, "d": 10, "l": 15, "m": 3,
    "A": ["x^9", "y", "y^2"], "B": ["1", "x^2", "x^7"],
    "term_labels": {"A1": "x^9", "A2": "y", "A3": "y^2", "B1": "1", "B2": "x^2", "B3": "x^7"},
    "HX": rows(evcode.HX), "HZ": rows(evcode.HZ), "LX": rows(evcode.LX), "LZ": rows(evcode.LZ),
}
json.dump(code_json, open(DATA / "code" / "bb90_code.json", "w"), separators=(",", ":"))
code = BC.load_code()
for a in ("HX", "HZ", "LX", "LZ"):
    assert (getattr(code, a) == np.asarray(getattr(evcode, a)) % 2).all()
print("bb90 code OK")

# ---------------------------------------------------------------- circuits
src = {
    "bb90_c16": ("search/experiments/e028/c16_spec.json",
                 "c16: [[90,8,10]] single-ancilla interleaved circuit, period 16 (non-wrapping frame: reset 0, CNOTs "
                 "in steps 1..12, measurement 15), translation invariant; d_circ = 10 for every R, both bases"),
    "bb90_u16": ("search/experiments/e028/u16_spec.json",
                 "u16: control circuit for [[90,8,10]], same template and extended code as c16; d_circ = 9 "
                 "(undetected logicals of weight 9 at R = 1, 2)"),
    "bb90_s16": ("results/E-028-bb90-interleaved/segctl_A1A2A3B2B1B3_A1A2A3B2B1B3.json",
                 "s16: segmentable control circuit for [[90,8,10]] (X checks: reset 0, CNOTs 1..6, measurement 7; Z checks: "
                 "reset 7, CNOTs 8..13, measurement 14), same per-check CNOT orders class and extended code as c16; d_circ = 8"),
}
specs = {}
for name, (path, desc) in src.items():
    d = json.load(open(path))
    d = {"format": d["format"], "name": desc, "period": d["period"], "x_checks": d["x_checks"], "z_checks": d["z_checks"]}
    s_pkg = PS.parse_schedule(d)
    s_ev = ev_parse({k: v for k, v in d.items() if k != "name"})
    assert not PS.validate_schedule(s_pkg, code), name
    for R in (1, 2, 3):
        cp = PS.build_circuits(s_pkg.canonical(), code, R)
        ce = ev_build(s_ev.canonical(), evcode, R)
        for b in "ZX":
            assert str(cp[b]) == str(ce[b]), (name, R, b)
            assert str(PN.add_sd6(cp[b])) == str(add_noise(ce[b], "sd6", 1e-3)), (name, R, b, "noise")
    json.dump(d, open(DATA / "circuits" / f"{name}.json", "w"), separators=(",", ":"))
    specs[name] = s_pkg
print("circuits OK (package template == evaluator template, noiseless and SD6, R = 1..3)")

# ---------------------------------------------------------------- extended codes + weight-8 / weight-9 lists
c16 = specs["bb90_c16"]
G = BE.order_group(c16)
assert len(G) == 45
xo, zo = c16.orders()
for basis, kind in (("Z", "X"), ("X", "Z")):
    keys, sups, supkey = BE.ext_columns(code, basis, c16)
    k2, _, _ = BE.ext_columns(code, basis, specs["bb90_u16"])
    assert set(k2) == set(keys), "u16 has a different extended code"
    k3, _, _ = BE.ext_columns(code, basis, specs["bb90_s16"])
    assert set(k3) == set(keys), "s16 has a different extended code"
    perms = BE.column_perms(code, basis, keys, sups, supkey, G)
    classes = BE.orbits(perms, len(keys))
    orb_of = {j: o for o, cl in enumerate(classes) for j in cl}
    H, L = BE.hl(code, basis)
    real = {k: [] for k in keys}
    for q in range(90):
        k = supkey.get((q,))
        if k is not None:
            real[k].append({"data_qubit": q})
    ords = xo if basis == "Z" else zo
    ctype = "X" if basis == "Z" else "Z"
    for i, o in enumerate(ords):
        for k in range(1, 6):
            s = tuple(sorted(o[k:]))
            if s in supkey:
                real[supkey[s]].append({"check": f"{ctype}{i}", "after_cnot": k, "residual": list(s)})
    cols = []
    for j, (k, s) in enumerate(zip(keys, sups)):
        v = np.zeros(90, np.uint8); v[list(s)] = 1
        h = np.flatnonzero((H @ v) % 2).tolist(); lv = np.flatnonzero((L @ v) % 2).tolist()
        cols.append({"index": j, "support": list(s), "kind": "data" if len(s) == 1 else "residual",
                     "H": h, "L": lv, "check_weight": len(h), "orbit": orb_of[j], "c16_realisations": real[k]})
    ext = {"description": f"Extended code of the {basis}-basis memory of the [[90,8,10]] circuit c16 "
                          f"({'X' if basis == 'Z' else 'Z'} errors; H = H{basis}, L = L{basis} of "
                          f"data/code/bb90_code.json; residuals from the {ctype}-check CNOT orders of c16). Column j: "
                          "representative support (data qubits), H = list of check rows with H s = 1, L = list of "
                          "logical rows with L s = 1. The control circuit u16 has the same set of columns.",
           "basis": basis, "num_columns": len(cols), "num_checks": int(H.shape[0]), "num_logicals": int(L.shape[0]),
           "translation_group": [list(g) for g in G], "orbits": classes, "columns": cols}
    json.dump(ext, open(DATA / "extended_code" / f"bb90_extended_code_{basis}_memory.json", "w"), separators=(",", ":"))
    assert BE.ext_keys_from_file(code, basis) == keys
    kidx = {k: j for j, k in enumerate(keys)}
    nH = H.shape[0]
    Hm, Lm = BE.key_matrices(keys, nH)
    # audit MITM lists (own logical basis): map each audit column to ours through its support
    au = pickle.load(open(f"results/E-028-audit/ext_c16_{kind}.pkl", "rb"))
    au_map = [kidx[BE.key_of(code, basis, au["cols"][k][0])] for k in au["keys"]]
    for w in (8, 9):
        d = pickle.load(open(f"results/E-028-bb90-interleaved/w{w}_{kind}_all_A1A2A3B2B1B3.pkl", "rb"))
        assert set(d["colset"]) == set(keys)
        found = {tuple(sorted(kidx[k] for k in S)) for S in d["keys"]}
        audit = {tuple(sorted(au_map[j] for j in S)) for S in au[f"s{w}"]}
        assert found == audit, (basis, w, len(found), len(audit))
        assert len(found) == {8: 585, 9: 16830}[w]
        entries, lorb = [], {}
        for S in sorted(found):
            x = np.zeros(len(keys), np.uint8); x[list(S)] = 1
            assert len(set(S)) == w and not ((Hm @ x) % 2).any() and ((Lm @ x) % 2).any()
            rep = min(tuple(sorted(p[j] for j in S)) for p in perms)
            lorb.setdefault(rep, len(lorb))
            entries.append({"columns": list(S), "orbit": lorb[rep],
                            "logical_flipped": np.flatnonzero((Lm @ x) % 2).tolist()})
        assert all(len({tuple(sorted(p[j] for j in S)) for p in perms}) == 45 for S in list(lorb)[:50])
        print(basis, "columns", len(keys), "column orbits", len(classes), f"weight-{w}", len(entries),
              "orbits", len(lorb))
        json.dump({"description": f"All weight-{w} logicals of the extended code of the {basis}-basis memory of "
                                  f"the [[90,8,10]] circuit c16 (d_ext = 8): each entry lists {w} distinct column "
                                  f"indices of data/extended_code/bb90_extended_code_{basis}_memory.json whose H parts "
                                  "sum to zero and whose L parts do not; 'orbit' numbers the orbits under the 45 "
                                  "translations; 'logical_flipped' = rows of L with odd sum.",
                   "basis": basis, "weight": w, "count": len(entries), "num_orbits": len(lorb), "logicals": entries},
                  open(DATA / "logicals" / f"bb90_weight{w}_logicals_{basis}_memory.json", "w"), separators=(",", ":"))
print("extended codes and lists OK (project DFS lists == audit MITM lists)")

# ---------------------------------------------------------------- weight-10 witness
inj = json.load(open("results/E-028-bb90-interleaved/inject10_c16_spec.json"))
wit = {}
for basis in "ZX":
    supp = inj[basis]["support"]
    H, L = BE.hl(code, basis)
    v = np.zeros(90, np.uint8); v[supp] = 1
    assert len(supp) == 10 and not ((H @ v) % 2).any() and ((L @ v) % 2).any()
    wit[basis] = {"type": "X" if basis == "Z" else "Z", "support": supp}
json.dump({"description": "Weight-10 logical operators of [[90,8,10]] used for the upper bound d_circ <= 10 of c16. "
                          "For the Z-basis memory an X-type logical (support on data qubits; commutes with HZ, "
                          "anticommutes with some rows of LZ), for the X-basis memory a Z-type logical. Applied as "
                          "single-qubit flips right after data initialisation (one SD6 reset fault each); verified by "
                          "code/bb90/inject_upper_bound.py for c16, R = 1, 2, 3, 6, 10, 13.",
           "witnesses": wit}, open(REL / "witnesses" / "bb90_upper_bound_weight10.json", "w"), indent=1)
print("witness OK")

# ---------------------------------------------------------------- d_ext <= 8 CNF (generated by code/bb90/dext_free.py)
cnf = Path(sys.argv[1]) if len(sys.argv) > 1 else None
ref = "results/E-028-audit/a6_dext_free_X.cnf"
sha = lambda p: hashlib.sha256(open(p, "rb").read()).hexdigest()  # noqa: E731
if cnf is not None:
    assert sha(cnf) == sha(ref), "regenerated CNF differs from the audit CNF"
    out = REL / "certificates" / "bb90_dext_free"
    out.mkdir(parents=True, exist_ok=True)
    with open(cnf, "rb") as fi, gzip.GzipFile(out / "X_side.cnf.gz", "wb", mtime=0) as fo:
        shutil.copyfileobj(fi, fo)
    print("CNF OK, sha256", sha(cnf))

# ---------------------------------------------------------------- DRAT proof record (certify.py one ... --keep output)
cert = Path(sys.argv[2]) if len(sys.argv) > 2 else None
if cert is not None:
    rec = json.loads([l for l in open(cert / "certify.out") if l.startswith("{")][-1])
    orig = "5fad1f63366a1ff468273d9712b4ead9157e35d05ec7570d4f9faedb80dbceb0"     # audit proof (2026 audit run)
    assert rec["ok"] and rec["cnf_sha256"] == sha(ref)
    name = "bb90_dext_free__X_side"
    rec.update({"name": name, "cnf": "certificates/bb90_dext_free/X_side.cnf.gz", "proof_shipped": False,
                "solver_build": "CaDiCaL 3.0.1 (tools/VERSIONS: commit c607304), -q --binary=true",
                "first_proof_sha256": orig, "regenerated_proof_identical": rec["drat_sha256"] == orig})
    PR = REL / "certificates" / "proofs"
    with open(PR / "bb90_dext_free.jsonl", "w") as f:
        f.write(json.dumps(rec) + "\n")
    for tool in ("cadical", "drat-trim", "cake_lpr"):
        src = cert / f"bb90_dext_free_X.{tool}.log"
        if src.exists():
            shutil.copyfile(src, PR / "logs" / f"{name}.{tool}.log")
    print("proof record:", rec["solver"], rec.get("drat_trim"), rec.get("cake_lpr"), "identical:",
          rec["regenerated_proof_identical"])

# ---------------------------------------------------------------- gross upper-bound witness: also R = 2
p = REL / "witnesses" / "upper_bound_weight12.json"
W12 = json.load(open(p))
W12["description"] = W12["description"].replace("R = 1, 3, 6, 10.", "R = 1, 2, 3, 6, 10.")
assert "R = 1, 2, 3, 6, 10." in W12["description"]
json.dump(W12, open(p, "w"))
print("upper_bound_weight12.json: description covers R = 1, 2, 3, 6, 10")
