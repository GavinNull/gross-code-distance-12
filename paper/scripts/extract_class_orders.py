"""Print the per-colour-class CNOT order and time steps of a gross-code schedule spec.

Used for Table I of paper/draft.tex (cand_p21) and Fig. 1 of paper/figures_plan.md.
Usage: uv run python paper/scripts/extract_class_orders.py <spec.json> [<reference spec, e.g. Fig. 12>]
  e.g.  ... search/experiments/e024a/cs_P18_H24.json results/E-021-gross-new-orders/fig12_spec.json
With a reference spec, the script also prints, per class, the element of the 8-element group
generated by reversal (rev), swap of positions 1,2 (s12) and swap of positions 5,6 (s56) that maps
the reference order to this order, and asserts that one exists (i.e. the order is in the Fig. 12 class).
Conventions: check index i = 6x + y on the 12 x 6 torus; colour = (x + y) mod 3;
A = x^3 + y + y^2 -> labels A1, A2, A3; B = y^3 + x + x^2 -> labels B1, B2, B3.
X check (x,y) acts on L qubit (x,y)+shift(A_k) and R qubit (x,y)+shift(B_k);
Z check (x,y) acts on L qubit (x,y)-shift(B_k) and R qubit (x,y)-shift(A_k).
The script asserts that this labelling reproduces every check's support and that
each (type, colour) class has a single (order, times) pattern. Order is cyclic from prep.
"""
import json
import sys
from collections import defaultdict

L, M = 12, 6
A = [("A1", (3, 0)), ("A2", (0, 1)), ("A3", (0, 2))]
B = [("B1", (0, 3)), ("B2", (1, 0)), ("B3", (2, 0))]


def idx(a, b):
    return 6 * (a % L) + (b % M)


def labels(i, typ):
    x, y = divmod(i, 6)
    out = {}
    if typ == "X":
        for n, (dx, dy) in A:
            out[idx(x + dx, y + dy)] = n
        for n, (dx, dy) in B:
            out[72 + idx(x + dx, y + dy)] = n
    else:
        for n, (dx, dy) in B:
            out[idx(x - dx, y - dy)] = n
        for n, (dx, dy) in A:
            out[72 + idx(x - dx, y - dy)] = n
    return out


def class_orders(path):
    d = json.load(open(path))
    P = d["period"]
    cls = defaultdict(set)
    for typ, key in (("X", "x_checks"), ("Z", "z_checks")):
        for i, c in enumerate(d[key]):
            lab = labels(i, typ)
            assert {q for q, _ in c["cnots"]} == set(lab), (typ, i)
            x, y = divmod(i, 6)
            prep = c["prep"]
            seq = tuple(
                (lab[q], t)
                for q, t in sorted(c["cnots"], key=lambda e: (e[1] - prep) % P)
            )
            cls[(typ, (x + y) % 3)].add((seq, prep, c["meas"]))
    out = {}
    for k in sorted(cls):
        assert len(cls[k]) == 1, k
        out[k] = next(iter(cls[k]))
    return P, out


def transform_name(ref, new):
    """Return the name of g in <rev, s12, s56> with g(ref) == new, or None."""
    def s12(o): return [o[1], o[0]] + o[2:]
    def s56(o): return o[:4] + [o[5], o[4]]
    def rev(o): return o[::-1]
    for r in (False, True):
        for a in (False, True):
            for b in (False, True):
                o = list(ref)
                name = []
                if r:
                    o = rev(o); name.append("rev")
                if a:
                    o = s12(o); name.append("s12")
                if b:
                    o = s56(o); name.append("s56")
                if o == list(new):
                    return "*".join(name) or "id"
    return None


def main(path, ref=None):
    P, cls = class_orders(path)
    refcls = class_orders(ref)[1] if ref else None
    print(f"period {P}")
    for k, (seq, prep, meas) in cls.items():
        line = (f"{k[0]}{k[1]}  prep {prep:2d}  meas {meas:2d}  order "
                + " ".join(n for n, _ in seq) + "  times " + " ".join(str(t) for _, t in seq))
        if refcls:
            g = transform_name([n for n, _ in refcls[k][0]], [n for n, _ in seq])
            assert g is not None, ("not in the reference class", k)
            line += f"  from-ref {g}"
        print(line)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
